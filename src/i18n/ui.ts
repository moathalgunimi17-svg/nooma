export const dict: Record<Locale, Dict> = { ar, en };
export type UIKey = keyof typeof ar;

export function useT(locale: Locale) {
  const d = dict[locale];
  return (key: UIKey, vars?: Record<string, string | number>) => {
    let s = d[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Arabic plural for product counts (0, 1, 2, 3–10, 11+). */
export function countLabel(locale: Locale, n: number): string {
  const t = useT(locale);
  if (n === 1) return t('shop.count1');
  if (n === 2) return t('shop.count2');
  if (locale === 'ar' && n > 10) return `${n} منتجاً`;
  return t('shop.count', { n });
}
