// Writes supabase/catalog.sql from src/data/products.ts, so place_order() knows the same
// products, sizes and prices as the shop. Run: npm run catalog:sql (Node 22.6+ reads the .ts file).
import { readFileSync, writeFileSync } from 'node:fs';
import { products } from '../src/data/products.ts';

// The schema pieces this list needs (code, price per size, the order function) are copied from
// setup.sql, so this one file is all Nooma ever has to paste — on a new or an older database.
const setup = readFileSync(new URL('../supabase/setup.sql', import.meta.url), 'utf8');
const between = (from, to) => {
  const a = setup.indexOf(from);
  const b = setup.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`setup.sql: could not find "${from}"`);
  return setup.slice(a, b + to.length);
};
const schema = [
  between("-- Nooma's product list", 'check (length(name_ar) <= 60);'),
  between('create or replace function public.place_order', 'grant execute on function public.place_order(jsonb) to anon, authenticated;'),
].join('\n\n');

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;
const ids = products.map((p) => q(p.id)).join(', ');

const productRows = products.map((p, i) => `  (${[
  q(p.id), q(p.code), q(p.slug), q(p.name.ar), q(p.name.en), q(p.categoryId),
  p.price === null ? 'null' : p.price.toFixed(3),
  p.sizePrices ? `${q(JSON.stringify(p.sizePrices))}::jsonb` : 'null',
  arr(p.sizeIds), p.featured, p.sample, 'true', i,
].join(', ')})`);

const colourRows = products.flatMap((p) => p.colourways.map((c, i) =>
  `  (${[q(p.id), q(c.id), q(c.name.ar), q(c.name.en), q(c.swatch), i].join(', ')})`));

const sql = `-- Nooma's products for the order system.
-- GENERATED by \`npm run catalog:sql\` from src/data/products.ts — do not edit by hand.
-- Paste this WHOLE file into Supabase → SQL Editor → Run. If Supabase warns about a
-- "destructive operation", choose "Run this query". Safe to run again after every change.
-- The last result should list all ${products.length} products.
begin;

${schema}

-- Anything not in the list (e.g. the old sample products) stops accepting orders.
update public.products set active = false where id not in (${ids});

insert into public.products (id, code, slug, name_ar, name_en, category_id, price, size_prices, size_ids, featured, sample, active, sort)
values
${productRows.join(',\n')}
on conflict (id) do update set
  code = excluded.code, slug = excluded.slug, name_ar = excluded.name_ar, name_en = excluded.name_en,
  category_id = excluded.category_id, price = excluded.price, size_prices = excluded.size_prices,
  size_ids = excluded.size_ids, featured = excluded.featured, sample = excluded.sample, active = true, sort = excluded.sort;

insert into public.colourways (product_id, id, name_ar, name_en, swatch, sort)
values
${colourRows.join(',\n')}
on conflict (product_id, id) do update set
  name_ar = excluded.name_ar, name_en = excluded.name_en, swatch = excluded.swatch, sort = excluded.sort;

commit;

select code, name_ar, price, size_prices from public.products where active order by sort;
`;

writeFileSync(new URL('../supabase/catalog.sql', import.meta.url), sql);
console.log(`supabase/catalog.sql: ${products.length} products`);
